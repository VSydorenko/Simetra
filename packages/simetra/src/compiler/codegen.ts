import {
  KIND_REGISTRY,
  versionColumn,
  type LocalizedString,
  type LogicalType,
  type MetadataRef,
  type PhysicalTable,
  type KindDefinition,
  type StandardColumnDef,
} from "simetra/model"
import type { CompiledModel } from "./compile"
import { compareStrings } from "./diagnostics"
import {
  entityFields,
  objectEntity,
  type EntityContext,
  type ValueSource,
} from "./entity-fields"
import { standardRefTargets, standardTargetRefs } from "./stages/model"

/** Джерело поля колонки: логічний опис або `{ raw }` стандартного реквізиту. */
type Source = ValueSource | { raw: string }

// Спека §8.5. Record за повним переліком логічних типів: новий тип без рядка
// тут не збереться.
const TS_OF_LOGICAL: Record<LogicalType, string> = {
  UUID: "string",
  Ref: "string",
  String: "string",
  Text: "string",
  Date: "string",
  DateTime: "string",
  Bytes: "string",
  Integer: "number",
  SmallInt: "number",
  // Не вміщуються в number без втрати точності: `BigInt` рантайм віддає
  // JS `bigint`, `Numeric` — десятковим рядком (спека П4 §6.4).
  BigInt: "bigint",
  Numeric: "string",
  Boolean: "boolean",
  // Через псевдонім `Json_`: голе `Json` у просторі імен може затінити
  // однойменний об'єкт.
  Json: "Json_",
}

const HEADER = "// Generated by simetra — do not edit"

// Власний JSDoc потрібен, щоб блок шапки не прилипнув до `Json` як його
// документація: TS прикріплює до оголошення попередній JSDoc незалежно від
// порожніх рядків.
const JSON_TYPE = [
  "/** Any JSON value. */",
  "export type Json = string | number | boolean | null | Json[] | { [key: string]: Json }",
].join("\n")

/** Відступ одного рівня вкладеності. */
const STEP = "  "

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/

/**
 * Стандартна колонка версії — за визначенням реєстру: рантайм віддає її
 * числом (поза безпечним цілим — відмова), а не `bigint` її логічного типу.
 */
const VERSION = versionColumn().logicalName

/**
 * Логічні TS-типи сутностей (спека §8.5) — вміст файлу оголошень `.d.ts`:
 * простір імен на кожен вид з таблицею (`Catalogs`, `Documents`, …), у ньому
 * інтерфейс на кожен об'єкт і кожну ТЧ. Простір імен знімає зіткнення
 * однакових логічних імен у різних видів, тож жодного перейменування
 * «першому — ім'я, іншим — префікс» немає: ім'я стабільне, поки його не
 * змінено в метаданих. Нуллабельність і генерованість беруться з фізичного
 * знімка, а не виводяться наново, тож тип не розійдеться з DDL. Порядок —
 * порядок реєстру видів, у просторі імен — за логічним іменем, тож додання
 * об'єкта не зсуває чужі інтерфейси.
 */
export function emitEntityTypes(model: CompiledModel): string {
  const byRef = new Map(
    model.objects.map((object) => [`${object.kind}.${object.name}`, object])
  )
  const lookup = (ref: MetadataRef) => byRef.get(`${ref.kind}.${ref.name}`)
  const refTargets = standardRefTargets(model.objects, model.project)
  // Заголовок виду скоупу живе лише в проєкті, а не в знімку скоупів.
  const scopeTitles = new Map(
    model.project.scopeKinds.map((k) => [k.id, k.title])
  )

  /**
   * Псевдоніми верхнього рівня `<Простір>_<Об'єкт>_<ТЧ>` і `Json_`. Усередині
   * просторів імен кожне посилання на тип іде лише через них: голе
   * `Documents.Sale.Goods` чи `Json` затінив би об'єкт із такою назвою
   * (довідник `Documents`, довідник `Json`), а TS не дає за це діагностики —
   * лише мовчки інший тип. Затінити псевдонім може лише простір імен або
   * ім'я об'єкта, а імена об'єктів — PascalCase без підкреслень (логічні
   * імена реквізитів підкреслення мають, але вони не оголошують типів).
   * Псевдоніми не експортуються (`export {}` в кінці файлу), тож публічний
   * контракт — лише `Json` і простори імен.
   */
  const aliases = new Map<string, string>()

  const refName = (ref: MetadataRef) =>
    JSON.stringify(`${ref.kind}.${ref.name}`)

  /**
   * Іменований тип перерахування чи PG-енаму — через псевдонім
   * `<Простір>_<Ім'я>`; ціль з таблицею — ключ `string`. Невідома ціль на
   * моделі без помилок недосяжна (її відсікає стадія зв'язків), тож `string`
   * там — безпечний запас, а не прихована поведінка.
   */
  const refType = (ref: MetadataRef): string => {
    const target = lookup(ref)
    if (target === undefined) return "string"
    const def = KIND_REGISTRY[target.kind]
    if (!declaresType(def)) return "string"
    const path = [pascal(def.dir), target.name]
    aliases.set(path.join("_"), path.join("."))
    return path.join("_")
  }

  const valueType = (
    source: Source,
    targets: readonly MetadataRef[] | undefined,
    paired: boolean
  ): { ts: string; nullable: boolean } => {
    // Сирий тип PG не має логічного відповідника: `unknown` — свідоме
    // рішення, а `null` у ньому вже міститься.
    if ("raw" in source || source.type === "Raw") {
      return { ts: "unknown", nullable: false }
    }
    let ts: string
    if (source.type === "PgEnum") {
      ts = source.enum === undefined ? "string" : refType(source.enum)
    } else if (paired) {
      const types = (targets ?? source.allowedTypes ?? []).map(refName)
      ts = `{ type: ${types.length === 0 ? "never" : types.join(" | ")}; id: string }`
    } else if (source.type === "Ref" && source.ref !== undefined) {
      ts = refType(source.ref)
    } else {
      ts = TS_OF_LOGICAL[source.type]
      if (source.type === "Json") aliases.set("Json_", "Json")
    }
    if (source.array === true) {
      ts = /[|{]/.test(ts) ? `(${ts})[]` : `${ts}[]`
    }
    return { ts, nullable: true }
  }

  /** `extra` — готові рядки останнього абзацу (список значень типу). */
  const doc = (
    indent: string,
    title: LocalizedString | undefined,
    description: LocalizedString | undefined,
    extra: readonly string[] = []
  ): string[] => {
    const lines = [
      pick(title),
      pick(description),
      extra.length === 0 ? undefined : extra.join("\n"),
    ]
      .filter((text): text is string => text !== undefined)
      // `*/` у тексті закрив би коментар достроково.
      .flatMap((text, index) => [
        ...(index > 0 ? [""] : []),
        ...text.replaceAll("*/", "*\\/").split("\n"),
      ])
    if (lines.length === 0) return []
    if (lines.length === 1) return [`${indent}/** ${lines[0]} */`]
    return [
      `${indent}/**`,
      ...lines.map((line) =>
        line === "" ? `${indent} *` : `${indent} * ${line}`
      ),
      `${indent} */`,
    ]
  }

  const emitFields = (
    table: PhysicalTable,
    context: EntityContext,
    targetsOf: (def: StandardColumnDef) => readonly MetadataRef[],
    overrides: ReadonlyMap<
      string,
      { title?: LocalizedString; description?: LocalizedString }
    >,
    member: string
  ): string[] => {
    const lines: string[] = []
    for (const field of entityFields(model, table, context)) {
      const { standard: def, element, scopeKindId } = field
      const paired = field.columns.length === 2
      let source: Source
      let targets: readonly MetadataRef[] | undefined
      let title: LocalizedString | undefined
      let description: LocalizedString | undefined
      if (def !== undefined) {
        source = def.type
        targets = def.ref === undefined ? undefined : targetsOf(def)
        const override = overrides.get(def.logicalName)
        title = override?.title ?? def.title
        description = override?.description
      } else if (element !== undefined) {
        source = element
        title = element.title
        description = element.description
      } else if (scopeKindId !== undefined) {
        // Носій скоупу: логічне ім'я — ім'я виду, тип — ключ кореня.
        source = { type: "UUID" }
        title = scopeTitles.get(scopeKindId)
        description = { en: `Value of the \`${field.name}\` scope kind.` }
      } else {
        // Колонка без походження в метаданих (не трапляється для видів 1С);
        // тип відомий лише фізично.
        source = {
          raw: table.columns.find((c) => c.name === field.columns[0])!.type,
        }
      }

      const { ts, nullable } =
        def?.logicalName === VERSION
          ? { ts: "number", nullable: true }
          : valueType(source, targets, paired)
      const readonly = field.generated ? "readonly " : ""
      lines.push(
        ...doc(member, title, description),
        `${member}${readonly}${fieldName(field.name)}: ${ts}${nullable && !field.notNull ? " | null" : ""}`
      )
    }
    return lines
  }

  /**
   * Простір імен іменованих типів виду: `export type <Ім'я> = "a" | "b"`.
   * Заголовок і опис типу — з метаданих об'єкта, заголовки значень — з подання
   * моделі (лише значення, що їх мають). Значення без заголовка в переліку
   * лишаються, щоб список відповідав union.
   */
  const emitTypeNamespace = (def: KindDefinition): string | undefined => {
    const items = model.objects
      .filter((object) => object.kind === def.kind)
      .map((object) => {
        const data = object.data as {
          title?: LocalizedString
          description?: LocalizedString
          values?: (string | { id?: string; name: string })[]
        }
        const titles = new Map(
          (
            model.presentation.objects.find((p) => p.objectId === object.id)
              ?.values ?? []
          ).map((value) => [value.id, pick(value.title)?.replaceAll("\n", " ")])
        )
        const values = (data.values ?? []).map((value) =>
          typeof value === "string"
            ? { name: value, title: undefined }
            : { name: value.name, title: titles.get(value.id ?? "") }
        )
        // Значення без елементів (факт реєстру `valueElements`, як у
        // PG-енама) заголовків не мають, але список міток читачеві корисний;
        // з елементами — перелік лише коли хоч одне має заголовок, бо інакше
        // список повторював би сам union.
        const listed =
          !def.valueElements || values.some(({ title }) => title !== undefined)
        const list = values.map(({ name, title }) =>
          title === undefined ? `- \`${name}\`` : `- \`${name}\`: ${title}`
        )
        return {
          name: object.name,
          text: [
            ...doc(
              STEP,
              data.title,
              data.description,
              listed ? ["Values:", ...list] : []
            ),
            `${STEP}export type ${object.name} = ${
              values.length === 0
                ? "never"
                : values.map(({ name }) => JSON.stringify(name)).join(" | ")
            }`,
          ].join("\n"),
        }
      })
    if (items.length === 0) return undefined
    items.sort((a, b) => compareStrings(a.name, b.name))
    return [
      `export declare namespace ${pascal(def.dir)} {`,
      items.map((item) => item.text).join("\n\n"),
      "}",
    ].join("\n")
  }

  /**
   * Предвизначені елементи — окремий простір імен верхнього рівня
   * `Predefined.<Об'єкт>`, як `Enumerations`: у просторі імен об'єкта його ТЧ
   * (`Catalogs.Item.Predefined` для ТЧ `predefined`) зіткнулися б з типом.
   * Лише union логічних імен: мітки — фізика (спека §8.5), мапу «ім'я ↔
   * мітка» дають адаптери джерел (П4).
   */
  const predefined: { name: string; text: string }[] = []
  const emitPredefined = (object: CompiledModel["objects"][number]) => {
    const def = KIND_REGISTRY[object.kind]
    const items = (def.namedElementFields ?? []).flatMap(
      (field) =>
        ((object.data as Record<string, unknown>)[field] ?? []) as {
          id?: string
          name: string
        }[]
    )
    if (items.length === 0) return undefined
    const descriptions = new Map(
      (
        model.presentation.objects.find((p) => p.objectId === object.id)
          ?.predefined ?? []
      ).map((item) => [item.id, pick(item.description)?.replaceAll("\n", " ")])
    )
    const described = items.map(({ id, name }) => ({
      name,
      description: descriptions.get(id ?? ""),
    }))
    // Перелік — лише коли хоч один елемент має опис, як у перерахувань.
    const list = described.some(({ description }) => description !== undefined)
      ? [
          "Items:",
          ...described.map(({ name, description }) =>
            description === undefined
              ? `- \`${name}\``
              : `- \`${name}\`: ${description}`
          ),
        ]
      : []
    const target = `${pascal(def.dir)}.${object.name}`
    predefined.push({
      name: object.name,
      text: [
        ...doc(
          STEP,
          { en: `Predefined items of {@link ${target}}.` },
          undefined,
          list
        ),
        `${STEP}export type ${object.name} = ${described
          .map(({ name }) => JSON.stringify(name))
          .join(" | ")}`,
      ].join("\n"),
    })
    return `Predefined items: {@link Predefined.${object.name}}.`
  }

  const namespaces: string[] = []
  for (const def of Object.values(KIND_REGISTRY)) {
    if (declaresType(def)) {
      const text = emitTypeNamespace(def)
      if (text !== undefined) namespaces.push(text)
      continue
    }
    if (def.materializes !== "table") continue
    const items: { name: string; text: string }[] = []
    for (const object of model.objects) {
      if (object.kind !== def.kind) continue
      const entity = objectEntity(model, object)
      if (entity === undefined) continue
      const { main, elements, sections } = entity

      const data = object.data as {
        title?: LocalizedString
        description?: LocalizedString
      }

      const targetsOf = (column: StandardColumnDef) =>
        standardTargetRefs(column, object.data, refTargets)
      const block = model.presentation.objects.find(
        (p) => p.objectId === object.id
      )
      const overrides = new Map(Object.entries(block?.standardAttributes ?? {}))

      const sectionNames = sections.map((section) => {
        const name = pascal(section.name)
        const path = [pascal(def.dir), object.name, name]
        return {
          section,
          name,
          alias: path.join("_"),
          target: path.join("."),
        }
      })

      // ТЧ — поле-масив і вкладений інтерфейс рядка, і з файлу, і стандартна.
      const body = emitFields(
        main,
        { standard: entity.standard, elements },
        targetsOf,
        overrides,
        STEP.repeat(2)
      )
      // У схемі ТЧ немає `description`, тож поле-масив несе лише заголовок.
      for (const { section, alias, target } of sectionNames) {
        aliases.set(alias, target)
        body.push(
          ...doc(STEP.repeat(2), section.title, undefined),
          `${STEP.repeat(2)}${fieldName(section.name)}: ${alias}[]`
        )
      }
      const predefinedLink = emitPredefined(object)
      const parts = [
        [
          ...doc(
            STEP,
            data.title,
            data.description,
            predefinedLink === undefined ? [] : [predefinedLink]
          ),
          `${STEP}export interface ${object.name} {`,
          ...body,
          `${STEP}}`,
        ].join("\n"),
      ]

      // ТЧ — вкладений простір імен власника (злиття з інтерфейсом):
      // `Documents.Sale.Goods` не зіштовхується з документом `SaleGoods`.
      const rows = [...sectionNames]
        .sort((a, b) => compareStrings(a.name, b.name))
        .flatMap(({ section, name }) => {
          const table = model.physical.tables.find(
            (candidate) =>
              candidate.origin.objectId === object.id &&
              candidate.origin.tabularSectionId === section.id
          )
          if (table === undefined) return []
          const inner = STEP.repeat(2)
          return [
            [
              ...doc(inner, section.title, undefined),
              `${inner}export interface ${name} {`,
              ...emitFields(
                table,
                { standard: section.standard, elements },
                targetsOf,
                new Map(
                  Object.entries(
                    block?.sections?.find((p) => p.sectionId === section.id)
                      ?.standardAttributes ?? {}
                  )
                ),
                STEP.repeat(3)
              ),
              `${inner}}`,
            ].join("\n"),
          ]
        })
      if (rows.length > 0) {
        parts.push(
          [
            `${STEP}export namespace ${object.name} {`,
            rows.join("\n\n"),
            `${STEP}}`,
          ].join("\n")
        )
      }
      items.push({ name: object.name, text: parts.join("\n\n") })
    }
    if (items.length === 0) continue
    // Порядок за ім'ям, а не за порядком файлів: додання об'єкта не зсуває
    // сусідів, а diff згенерованого файлу лишається мінімальним.
    items.sort((a, b) => compareStrings(a.name, b.name))
    namespaces.push(
      [
        `export declare namespace ${pascal(def.dir)} {`,
        items.map((item) => item.text).join("\n\n"),
        "}",
      ].join("\n")
    )
  }
  if (predefined.length > 0) {
    predefined.sort((a, b) => compareStrings(a.name, b.name))
    namespaces.push(
      [
        "export declare namespace Predefined {",
        predefined.map((item) => item.text).join("\n\n"),
        "}",
      ].join("\n")
    )
  }
  const aliasLines = [...aliases]
    .sort(([a], [b]) => compareStrings(a, b))
    .map(([alias, target]) => `type ${alias} = ${target}`)
  const title = pick(model.project.title)
  return `${[
    HEADER,
    ...(title === undefined
      ? []
      : [
          [
            "/**",
            ...title
              .replaceAll("*/", "*\\/")
              .split("\n")
              .map((line) => (line === "" ? " *" : ` * ${line}`)),
            " *",
            " * @packageDocumentation",
            " */",
          ].join("\n"),
        ]),
    JSON_TYPE,
    ...namespaces,
    ...(aliasLines.length === 0 ? [] : [aliasLines.join("\n")]),
    // Робить псевдоніми приватними: у `.d.ts` без явного експорту все
    // оголошене на верхньому рівні вважається експортованим.
    "export {}",
  ].join("\n\n")}\n`
}

/**
 * Вид оголошує іменований тип значень (перерахування, PG-енам), а не таблицю:
 * факт реєстру, а не ім'я виду.
 */
function declaresType(def: KindDefinition): boolean {
  return def.materializes === "enumType" || def.valueElements
}

function pick(text: LocalizedString | undefined): string | undefined {
  return text?.en ?? text?.uk
}

function fieldName(name: string): string {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name)
}

/** `order_items` і `orderItems` дають однаковий PascalCase-хвіст імені. */
function pascal(name: string): string {
  return name
    .split(/[^A-Za-z0-9]+/)
    .filter((part) => part !== "")
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join("")
}
